"""Real browser smoke test. Uses a disposable database and the installed Edge browser."""
import sys
import tempfile
import threading
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app import create_app
from playwright.sync_api import expect, sync_playwright
from werkzeug.serving import make_server


def main():
    with tempfile.TemporaryDirectory() as tmp:
        app = create_app({'TESTING': True, 'DATABASE': str(Path(tmp) / 'browser.db')})
        server = make_server('127.0.0.1', 0, app, threaded=True)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            with sync_playwright() as p:
                browser = p.chromium.launch(channel='msedge', headless=True)
                context = browser.new_context(viewport={'width': 1440, 'height': 1000})
                page = context.new_page()
                errors = []
                page.on('pageerror', lambda error: errors.append(str(error)))
                page.goto(f'http://127.0.0.1:{server.server_port}')
                expect(page.locator('#login-screen')).to_be_visible()
                page.locator('#username').fill('Monke')
                page.locator('#login-password').fill('monkeman')
                page.locator('#login-form button').click()
                expect(page.locator('#password-screen')).to_be_visible()
                page.locator('#current-password').fill('monkeman')
                page.locator('#new-password').fill('browser-admin-password')
                page.locator('#confirm-password').fill('browser-admin-password')
                page.locator('#password-form .primary').click()
                expect(page.locator('#workspace')).to_be_visible()
                page.locator('#new-column').click()
                page.locator('#column-name').fill('Review')
                page.locator('#column-type').select_option('doing')
                page.locator('#column-submit').click()
                expect(page.locator('#column-dialog')).not_to_be_visible()
                review = page.get_by_role('region', name='Review', exact=True)
                # Sections have an accessible name and are therefore regions.
                expect(review).to_be_visible()
                review.get_by_role('button', name='Configurações de Review').click()
                page.locator('#column-type').select_option('done')
                page.locator('#column-submit').click()
                expect(page.locator('#column-dialog')).not_to_be_visible()
                review.get_by_role('button', name='+ Adicionar tarefa').click()
                page.locator('#title').fill('Browser task')
                page.locator('#description').fill('Original description')
                page.locator('#assignee-picker').click()
                page.locator('#assignee-options label').filter(has_text='Monke').locator('input').check()
                page.locator('#save-task').click()
                expect(page.locator('#form-title')).to_have_text('Detalhes da tarefa')
                dxf = b'0\r\nSECTION\r\n2\r\nENTITIES\r\n0\r\nENDSEC\r\n0\r\nEOF\r\n'
                page.locator('#files').set_input_files({'name': 'browser.dxf', 'mimeType': 'application/octet-stream', 'buffer': dxf})
                page.locator('#upload-form button').click()
                expect(page.get_by_role('link', name='browser.dxf')).to_be_visible()
                expect(page.locator('#task-history')).to_contain_text('enviou o arquivo')
                with page.expect_download() as download_info:
                    page.get_by_role('link', name='browser.dxf').click()
                assert Path(download_info.value.path()).read_bytes() == dxf
                page.locator('#description').fill('Automatically saved description')
                expect(page.locator('#notice')).to_have_text('Alterações salvas.')
                # Wait for the actual autosave, rather than an earlier success message.
                page.wait_for_function("savedTaskFields.includes('Automatically saved description')")
                page.locator('#cancel').click()
                expect(page.locator('#dialog')).not_to_be_visible()
                page.reload()
                expect(page.locator('#workspace')).to_be_visible()
                expect(page.locator('#summary')).to_contain_text('1 concluída')
                expect(page.locator('.card')).to_contain_text('Automatically saved description')
                page.locator('#my-tasks').click()
                expect(page.locator('.card')).to_have_count(1)
                page.locator('#assignee-filter').select_option(label='Monke')
                expect(page.locator('#my-tasks')).to_have_attribute('aria-pressed', 'false')
                expect(page.locator('.card')).to_have_count(1)
                page.locator('#assignee-filter').select_option('')
                card = page.locator('.card')
                target = page.get_by_role('region', name='Em andamento', exact=True)
                card.drag_to(target)
                expect(target.locator('.card')).to_contain_text('Browser task')
                expect(page.locator('#summary')).to_contain_text('0 concluídas')
                page.get_by_role('button', name='Detalhes / Editar', exact=True).click()
                snapshot = page.evaluate('({id:board.id, version:board.version, csrf})')
                concurrent = page.request.post(f'http://127.0.0.1:{server.server_port}/api/boards/' + snapshot['id'] + '/columns',
                    headers={'X-CSRF-Token': snapshot['csrf']},
                    data={'name': 'Another user column', 'type': 'todo', 'version': snapshot['version']})
                assert concurrent.status == 201
                page.locator('#description').fill('Unsaved conflicting draft')
                expect(page.locator('#dialog .dialog-feedback')).to_contain_text('Outra pessoa alterou este item')
                expect(page.locator('#description')).to_have_value('Unsaved conflicting draft')
                remote = page.request.get(f'http://127.0.0.1:{server.server_port}/api/boards/' + snapshot['id']).json()['board']
                assert remote['tasks'][0]['description'] == 'Automatically saved description'
                page.once('dialog', lambda dialog: dialog.accept())
                page.locator('#cancel').click()
                page.locator('#refresh').click()
                expect(page.get_by_role('region', name='Another user column', exact=True)).to_be_visible()
                page.locator('#activity-menu').click()
                expect(page.locator('#activity-screen')).to_be_visible()
                expect(page.locator('#activity-list')).to_contain_text('moveu a tarefa')
                page.locator('#activity-action').select_option('attachment.uploaded')
                page.locator('#activity-filters .primary').click()
                expect(page.locator('#activity-list .log-entry')).to_have_count(1)
                expect(page.locator('#activity-list')).to_contain_text('browser.dxf')
                page.locator('#activity-list').get_by_role('button', name='Ver histórico da tarefa').click()
                expect(page.locator('#standalone-history')).to_contain_text('criou a tarefa')
                expect(page.locator('#standalone-history')).to_contain_text('atribuiu o usuário')
                page.locator('#history-close').click()
                page.locator('#activity-start').fill('2099-01-01')
                page.locator('#activity-filters .primary').click()
                expect(page.locator('#activity-list')).to_contain_text('Nenhuma atividade encontrada')
                page.locator('#activity-clear').click()
                expect(page.locator('#activity-list')).to_contain_text('moveu a tarefa')
                page.locator('#settings').click()
                expect(page.locator('#admin')).to_be_visible()
                page.locator('#new-user').click()
                page.locator('#user-name').fill('read-only')
                page.locator('#user-role').select_option('Viewer')
                expect(page.locator('[data-permission="edit_tasks"]')).not_to_be_checked()
                expect(page.locator('[data-permission="download_attachments"]')).to_be_checked()
                expect(page.locator('[data-permission="delete_own_attachments"]')).not_to_be_checked()
                expect(page.locator('[data-permission="view_task_history"]')).to_be_checked()
                expect(page.locator('[data-permission="assign_users"]')).not_to_be_checked()
                page.locator('#temporary-password').fill('viewer-temp-password')
                page.locator('#save-user').click()
                expect(page.locator('#user-dialog')).not_to_be_visible()
                expect(page.locator('#users-list')).to_contain_text('read-only')
                page.locator('#profile-menu-toggle').click()
                page.locator('#logout').click()
                expect(page.locator('#login-screen')).to_be_visible()
                page.locator('#username').fill('read-only')
                page.locator('#login-password').fill('viewer-temp-password')
                page.locator('#login-form button').click()
                expect(page.locator('#password-screen')).to_be_visible()
                page.locator('#current-password').fill('viewer-temp-password')
                page.locator('#new-password').fill('viewer-real-password')
                page.locator('#confirm-password').fill('viewer-real-password')
                page.locator('#password-form .primary').click()
                expect(page.locator('#workspace')).to_be_visible()
                expect(page.locator('#settings')).not_to_be_visible()
                expect(page.locator('#new')).not_to_be_visible()
                expect(page.locator('#new-column')).not_to_be_visible()
                expect(page.locator('#activity-menu')).not_to_be_visible()
                page.locator('#my-tasks').click()
                expect(page.locator('.card')).to_have_count(0)
                page.locator('#my-tasks').click()
                page.get_by_role('button', name='Detalhes', exact=True).click()
                expect(page.locator('#title')).to_be_disabled()
                expect(page.locator('#assignees')).to_be_disabled()
                expect(page.locator('#task-history')).to_contain_text('moveu a tarefa')
                expect(page.locator('#upload-form')).not_to_be_visible()
                expect(page.get_by_role('button', name='Excluir arquivo')).not_to_be_visible()
                expect(page.get_by_role('link', name='browser.dxf')).to_be_visible()
                page.locator('#cancel').click()
                page.set_viewport_size({'width': 390, 'height': 844})
                assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
                page.reload()
                expect(page.locator('#profile-name')).to_contain_text('read-only')
                assert not errors, errors
                browser.close()
                print('PASS: browser login, forced password change, column types, tasks, autosave, conflict draft protection, DXF upload/download, refresh, drag-and-drop, administration, viewer permissions, mobile layout')
        finally:
            server.shutdown()
            thread.join(timeout=5)
            server.server_close()


if __name__ == '__main__':
    main()
